"""Writes core/include/wxl/gx/slots.def: the stock D3D9 devices' vtable slots, and which of them
the Vulkan renderer takes over on the stock client.

The stock Wow.exe 12340 makes its Direct3D 9 device as a CGxDeviceD3d (vtable 0x00A2E718) or a
CGxDeviceD3d9Ex (0x00A2F500), 84 slots each, in CGxDevice's virtual order. Under
`[gx] api = vulkan` the runtime gives the device a copy of its vtable in which every slot that
reaches Direct3D 9 calls the Vulkan front instead (src/gx/x86/). This tool writes one row per slot:

    WXL_GX_SLOT(index, name, ret, params, pops, kind, d3d9, d3d9_at, d3d9ex, d3d9ex_at)

index   the slot, 0..83
name    the fork's virtual, an overload told apart by a suffix (DeviceCreateOnWindow)
ret     what it answers, in C terms (void*, int32_t, bool, float, void)
params  its parameters in C terms, `void* self` first (references and objects as pointers, enums
        as uint32_t, CImVector by value as uint32_t)
pops    the bytes the slot pops (__thiscall: every stack parameter, 4 each)
kind    keep    the stock entry stays: a CGxDevice function (the base class, which cannot reach
                the D3D9 device's members), an empty body, or one of KEEP_OVERRIDES below
        front   the runtime's thunk (src/gx/x86/Slots.cpp), which calls the Vulkan front
d3d9    the stock entry of CGxDeviceD3d's vtable at that index, as a seam's symbol column
        ("name" or "name@0x..."); "" for an entry the fork does not tag (an empty body, the
        D3D9Ex device's deleting destructor)
d3d9_at its address
d3d9ex, d3d9ex_at  the same in CGxDeviceD3d9Ex's

and one row per vtable:

    WXL_GX_VTABLE(api, address, slots, factory)

factory  the function that makes that device (cdecl, no parameter, answers the new device), where
         the runtime gives a new device its copy of the vtable

The order of the slots is MSVC's: the fork's declaration order, with overloads grouped where the
first is declared and laid out in the reverse of their declaration order. Every slot's stock
entry is held to the fork's name for it, so a wrong order fails here. check_conventions.py holds
each row against Wow.exe (convention, pops, the entries, and that a kept slot reads no member past
CGxDevice's).

Standard library only. --check compares with the file written and fails on a difference.
"""

import argparse
import os
import pathlib
import re
import struct
import sys

VTABLES = (("d3d9", 0x00A2E718), ("d3d9ex", 0x00A2F500))
# The function of the stock client that makes each device (cdecl, no parameter, the new device).
FACTORIES = {"d3d9": "CreateCGxDeviceD3d", "d3d9ex": "CreateCGxDeviceD3d9Ex"}
SLOT_COUNT = 84

# A slot whose stock entry is the D3D9 device's own, kept anyway: the reason it reaches nothing of
# Direct3D 9 (check_conventions.py proves it reads no member past CGxDevice's).
KEEP_OVERRIDES = {
    "DeviceReadDepths": "clamps the rectangle to the window and answers zeros: CGxDevice's members only",
}

# Overloads: the suffix that tells each one apart, by its first parameter's type.
OVERLOAD_SUFFIX = {
    ("DeviceCreate", "void*"): "OnWindow",
    ("DeviceCreate", "GxWindowProc"): "",
    ("DeviceSetGamma", "float"): "",
    ("DeviceSetGamma", "const CGxGammaRamp&"): "Ramp",
}

HEADER = """// SPDX-License-Identifier: MIT
// Copyright (c) 2026 WarcraftXL
//
// The stock D3D9 devices' vtable slots (Wow.exe 12340), and which of them the Vulkan renderer
// takes over on the stock client.
//
// GENERATED by core/tools/gx/generate_slots.py from the client fork's CGxDevice.h and OFFSET tags
// and from the two vtables of Wow.exe. Do not edit: re-run the tool and review the diff.
// check_conventions.py holds every row against Wow.exe.
//
//   WXL_GX_VTABLE(api, address, slots, factory)
//   WXL_GX_SLOT(index, name, ret, params, pops, kind, d3d9, d3d9_at, d3d9ex, d3d9ex_at)
//
//   factory the function that makes the device of that vtable: cdecl, no parameter, the device
//   index   the slot
//   name    the fork's virtual (an overload carries a suffix)
//   ret     what it answers, in C terms
//   params  its parameters in C terms, `void* self` first
//   pops    the bytes it pops: __thiscall, `this` in ECX, every other parameter on the stack
//   kind    keep: the stock entry stays (CGxDevice's own, an empty body, or a D3D9 one that
//           reads only CGxDevice's members); front: the runtime's thunk into the Vulkan front
//   d3d9    the stock entry of CGxDeviceD3d's vtable, as a seam's symbol column ("" when the fork
//           tags no function there: an empty body, or the D3D9Ex device's deleting destructor)
//   d3d9_at its address
//   d3d9ex, d3d9ex_at  the same in CGxDeviceD3d9Ex's

#ifndef WXL_GX_SLOT
#define WXL_GX_SLOT(index, name, ret, params, pops, kind, d3d9, d3d9_at, d3d9ex, d3d9ex_at)
#endif
#ifndef WXL_GX_VTABLE
#define WXL_GX_VTABLE(api, address, slots, factory)
#endif

"""

FOOTER = """
#undef WXL_GX_SLOT
#undef WXL_GX_VTABLE
"""

VIRTUAL = re.compile(r"^\s*virtual\s+(.*?)\s*(~?\w+)\s*\(([^)]*)\)\s*(?:const\s*)?(?:=\s*0\s*)?;", re.M)
OFFSET = re.compile(r"^// OFFSET: \[?0x([0-9A-Fa-f]{8})")
DEFINITION = re.compile(r"([\w:~<>]+)\s*\(")


# --- The fork ---------------------------------------------------------------------------------

def c_type(fork):
    """A parameter or result type of the fork in the C terms the row speaks."""
    t = " ".join(fork.split())
    if t == "void":
        return "void"
    if t.endswith("&") or t.endswith("*"):
        return "const void*" if t.startswith("const ") and not t.endswith("*&") else "void*"
    if t in ("int32_t", "uint32_t", "float", "bool", "uintptr_t"):
        return "uint32_t" if t == "uintptr_t" else t
    if t in ("GxWindowProc", "GxDeviceCallback", "GxTexUserFunc"):
        return "void*"
    if t in ("CImVector", "CGxTexFlags"):
        return "uint32_t"
    if t.startswith("E"):
        return "uint32_t"
    raise SystemExit("generate_slots: no C type for the fork's `%s`" % fork)


def split_params(text):
    text = text.strip()
    if not text or text == "void":
        return []
    out, depth, start = [], 0, 0
    for i, ch in enumerate(text):
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        elif ch == "," and depth == 0:
            out.append(text[start:i].strip())
            start = i + 1
    out.append(text[start:].strip())
    return out


def param_type(decl):
    """`const CGxFormat& format` -> `const CGxFormat&`."""
    match = re.match(r"(.*?[\s*&])(\w+)$", decl)
    return " ".join((match.group(1) if match else decl).split()).replace(" &", "&").replace(" *", "*")


def virtuals(client):
    header = (client / "Engine/Source/Gx/CGxDevice/CGxDevice.h").read_text(encoding="utf-8", errors="replace")
    found = []
    for match in VIRTUAL.finditer(header):
        ret, name, params = match.group(1).strip(), match.group(2), match.group(3)
        if ret.endswith("~"):
            ret, name = ret[:-1].strip() or "void", "~" + name
        found.append({"name": name, "ret": ret.strip(), "params": [param_type(p) for p in split_params(params)]})
    return found


def msvc_order(declared):
    """MSVC lays overloads out together where the first is declared, the last declared first."""
    groups, order = {}, []
    for v in declared:
        if v["name"] not in groups:
            groups[v["name"]] = []
            order.append(v["name"])
        groups[v["name"]].append(v)
    out = []
    for name in order:
        out.extend(reversed(groups[name]))
    return out


def tagged_names(client):
    """address -> (qualified name, parameter types) from the fork's OFFSET tags of Gx."""
    names = {}
    for path in sorted((client / "Engine/Source/Gx").rglob("*.cpp")):
        lines = path.read_text(encoding="utf-8", errors="replace").split("\n")
        for i, line in enumerate(lines):
            match = OFFSET.match(line)
            if not match:
                continue
            for j in range(i + 1, min(i + 4, len(lines))):
                if "(" in lines[j] and not lines[j].lstrip().startswith("//"):
                    head = DEFINITION.search(lines[j])
                    params = lines[j][lines[j].index("(") + 1:]
                    params = params[:params.rfind(")")] if ")" in params else params
                    if head:
                        names.setdefault(int(match.group(1), 16),
                                         (head.group(1), [param_type(p) for p in split_params(params)]))
                    break
    return names


# --- Wow.exe ----------------------------------------------------------------------------------

class Image:
    def __init__(self, path):
        self.data = pathlib.Path(path).read_bytes()
        pe = struct.unpack_from("<I", self.data, 0x3C)[0]
        count = struct.unpack_from("<H", self.data, pe + 6)[0]
        optional = struct.unpack_from("<H", self.data, pe + 20)[0]
        self.base = struct.unpack_from("<I", self.data, pe + 24 + 28)[0]
        self.sections = []
        at = pe + 24 + optional
        for i in range(count):
            name, vsize, va, rsize, raw = struct.unpack_from("<8sIIII", self.data, at + 40 * i)
            self.sections.append((name.rstrip(b"\0").decode(), va, vsize, raw, rsize))

    def read(self, address, size):
        rva = address - self.base
        for _, va, vsize, raw, rsize in self.sections:
            if va <= rva < va + max(vsize, rsize):
                return self.data[raw + rva - va:raw + rva - va + size]
        raise SystemExit("generate_slots: 0x%08X is outside Wow.exe's sections" % address)

    def dwords(self, address, count):
        return list(struct.unpack("<%dI" % count, self.read(address, 4 * count)))


def stub_pops(image, address):
    """The bytes an empty body (`ret` or `ret n`) pops, or None when the body is not empty."""
    code = image.read(address, 3)
    if code[0] == 0xC3:
        return 0
    if code[0] == 0xC2:
        return struct.unpack_from("<H", code, 1)[0]
    return None


# --- The rows ---------------------------------------------------------------------------------

def slot_rows(client, image):
    declared = virtuals(client)
    if len(declared) != SLOT_COUNT:
        raise SystemExit("generate_slots: CGxDevice.h declares %d virtuals, not %d" % (len(declared), SLOT_COUNT))
    ordered = msvc_order(declared)
    names = tagged_names(client)
    tables = {api: image.dwords(address, SLOT_COUNT) for api, address in VTABLES}
    counts = {}
    for v in declared:
        counts[v["name"]] = counts.get(v["name"], 0) + 1

    rows = []
    for index, v in enumerate(ordered):
        name = v["name"]
        if counts[name] > 1:
            key = (name, v["params"][0] if v["params"] else "")
            if key not in OVERLOAD_SUFFIX:
                raise SystemExit("generate_slots: overload %s(%s) has no suffix" % (name, ", ".join(v["params"])))
            name += OVERLOAD_SUFFIX[key]
        if v["name"].startswith("~"):
            name, ret, params = "Destructor", "void*", ["void* self", "uint32_t flags"]
        else:
            ret = c_type(v["ret"])
            params = ["void* self"] + ["%s a%d" % (c_type(p), i) for i, p in enumerate(v["params"])]
        pops = 4 * (len(params) - 1)

        entries, symbols, kinds = {}, {}, set()
        for api, _ in VTABLES:
            address = tables[api][index]
            entries[api] = address
            tagged = names.get(address)
            stub = stub_pops(image, address)
            if tagged and stub is not None and tagged[0].split("::")[-1] != v["name"]:
                tagged = None             # an empty body folded with another function's
            if tagged:
                qualified, tagged_params = tagged
                short = qualified.split("::")[-1]
                if short != v["name"] and not (v["name"].startswith("~") and short.startswith("~")) and stub is None:
                    raise SystemExit("generate_slots: slot %d of %s is %s at 0x%08X, but the fork's order says %s"
                                     % (index, api, qualified, address, v["name"]))
                if short == v["name"] and tagged_params != v["params"]:
                    raise SystemExit("generate_slots: slot %d of %s is %s(%s), but the fork's order says %s(%s)"
                                     % (index, api, qualified, ", ".join(tagged_params), v["name"], ", ".join(v["params"])))
                same = [a for a, n in names.items() if n[0] == qualified]
                symbols[api] = qualified if len(same) == 1 else "%s@0x%08X" % (qualified, address)
                if qualified.startswith("CGxDevice::"):
                    kinds.add("base")
                elif short in KEEP_OVERRIDES:
                    kinds.add("allowed")
                else:
                    kinds.add("device")
            elif v["name"].startswith("~"):
                symbols[api] = ""
                kinds.add("device")
            elif stub is not None:
                if stub != pops:
                    raise SystemExit("generate_slots: slot %d (%s) of %s is an empty body popping %d, not %d"
                                     % (index, name, api, stub, pops))
                symbols[api] = ""
                kinds.add("stub")
            else:
                raise SystemExit("generate_slots: slot %d (%s) of %s, 0x%08X, has no OFFSET tag in the fork"
                                 % (index, name, api, address))
        same_entry = entries["d3d9"] == entries["d3d9ex"]
        kind = "keep" if same_entry and kinds <= {"base", "stub", "allowed"} else "front"
        rows.append({"index": index, "name": name, "ret": ret, "params": params, "pops": pops, "kind": kind,
                     "d3d9": symbols["d3d9"], "d3d9ex": symbols["d3d9ex"],
                     "d3d9_at": entries["d3d9"], "d3d9ex_at": entries["d3d9ex"],
                     "why": KEEP_OVERRIDES.get(v["name"]) if kind == "keep" and "allowed" in kinds else None})
    return rows


def render(rows):
    out = [HEADER]
    for api, address in VTABLES:
        out.append('WXL_GX_VTABLE(%s, 0x%08X, %d, "%s")\n' % (api, address, SLOT_COUNT, FACTORIES[api]))
    out.append("\n")
    for r in rows:
        if r["why"]:
            out.append("// kept: %s\n" % r["why"])
        out.append('WXL_GX_SLOT(%d, %s, %s, (%s), %d, %s, "%s", 0x%08X, "%s", 0x%08X)\n'
                   % (r["index"], r["name"], r["ret"], ", ".join(r["params"]), r["pops"], r["kind"], r["d3d9"], r["d3d9_at"],
                      r["d3d9ex"], r["d3d9ex_at"]))
    out.append(FOOTER)
    return "".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--client", required=True, type=pathlib.Path, help="the client fork's checkout")
    parser.add_argument("--binary", default=os.environ.get("WXL_WOW_EXE"),
                        help="the stock Wow.exe 12340; default $WXL_WOW_EXE")
    parser.add_argument("--out", type=pathlib.Path,
                        default=pathlib.Path(__file__).resolve().parents[2] / "include" / "wxl" / "gx" / "slots.def",
                        help="slots.def to write or check")
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()
    if not args.binary:
        print("generate_slots: no Wow.exe: pass --binary or set WXL_WOW_EXE", file=sys.stderr)
        return 2

    rows = slot_rows(args.client, Image(args.binary))
    text = render(rows)
    front = sum(1 for r in rows if r["kind"] == "front")
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current != text:
            print("%s is not what the fork and Wow.exe give: run generate_slots.py and review the diff" % args.out,
                  file=sys.stderr)
            return 1
        print("%s: %d slots, %d taken by the Vulkan front, as the fork and Wow.exe give them" % (args.out, len(rows), front))
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s: %d slots, %d taken by the Vulkan front" % (args.out, len(rows), front))
    return 0


if __name__ == "__main__":
    sys.exit(main())
