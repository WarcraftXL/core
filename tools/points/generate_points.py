# Generates the tables of wxl.point from core/include/wxl/points/points.txt.
"""Generate the point tables from points.txt, or check them, or report their x86 coverage.

One list, three tables, each for the side that reads it:

  sdk/include/wxl/points.def        the contract: every point's name, lowered signature, layout
                                    hash, policy, thread, stability and runtimes. The C++ facade
                                    and the runtimes' service read it.
  core/include/wxl/points/x86.def   the stock client's side: address, length and convention of
                                    every point x86 can detour, and the sites of inlined copies.
  client/WarcraftXL/Points.gen.h    the recompiled client's side: one WXL_POINT_<n>(...) macro per
                                    point, which insert_points.py writes at the head of its function.

--check fails when a file is not what the list and the fork give (a pull that renamed a parameter,
a retype that changed a lowered signature, a list edited without regenerating). --coverage reads
Wow.exe and compares each point's calls there with its call sites in the fork: a function the 2008
compiler inlined into a caller has a call site in the source and no call in the binary, and its
x86 detour does not see that caller (a site line covers it).
"""

import argparse
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import points_table as table  # noqa: E402

CORE = HERE.parent.parent
HEADER = """// SPDX-License-Identifier: MIT
// Copyright (c) 2026 WarcraftXL
//
// GENERATED by core/tools/points/generate_points.py from core/include/wxl/points/points.txt.
// Do not edit: change points.txt and run the tool again.
"""


def column_hex(value):
    return "0x%08X" % value


# --- sdk/include/wxl/points.def ----------------------------------------------------------------

def contract_def(points):
    out = [HEADER, """//
// The points of wxl.point, in id order (a point's id is its row's position, from 1). Columns:
//
//   WXL_POINT(Ident, name, ret, params, lowered, layout_hash, policy, thread, stability, runtimes)
//
//   Ident        the point as a C identifier: wxl::points::Ident in the C++ facade
//   name         its name, the fork's qualified name when it was listed; what find() takes
//   ret, params  its signature as the contract carries it: every pointer is void*, `self` first
//                for a member function
//   lowered      the same reduced to sizes and classes, e.g. "i32(ptr,u32)"
//   layout_hash  FNV-1a of `lowered`: a mod built against another signature is refused
//   policy       replace (Before, Replace, After) or observe (Before, After)
//   thread       main or any (C and C++ handlers only)
//   stability    stable or provisional
//   runtimes     both, x86 (the stock client's runtime only) or x64 (the recompiled client's only)

#ifndef WXL_POINT
#error "define WXL_POINT(Ident, name, ret, params, lowered, layout_hash, policy, thread, stability, runtimes) before including wxl/points.def"
#endif

"""]
    for p in points:
        params = ", ".join("%s %s" % (t, n) for t, n in p.contract_params())
        if p.note:
            out.append("// %s\n" % p.note)
        out.append('WXL_POINT(%s, "%s", %s, (%s), "%s", %su, %s, %s, %s, %s)\n'
                   % (p.ident, p.name, p.ret_kind[1], params, p.lowered, column_hex(p.layout_hash),
                      p.policy, p.thread, p.stability, p.runtimes))
    out.append(MSVC_TAIL)
    return "".join(out)


# --- core/include/wxl/points/x86.def -----------------------------------------------------------

# MSVC takes a file whose first directive is #ifndef X and whose last is its #endif for one guarded
# by X, and skips it when it is included again with X defined: a table read several times in one
# translation unit ends with a directive of its own.
MSVC_TAIL = """
// MSVC takes a file that expands to nothing outside its opening #ifndef X ... #endif for one
// guarded by X, and skips it when it is included again with X defined: this table is read
// several times in one translation unit, under shapes that may leave it empty. A directive
// after the rows keeps it from looking guarded.
#ifdef WXL_TABLE_END
#endif
"""


def x86_def(points):
    out = [HEADER, """//
// The points the stock client's runtime detours, as data. Columns:
//
//   WXL_POINT_X86(Ident, name, address, length, conv, ret, params)
//       a point of wxl/points.def with an x86 body: its address in Wow.exe 12340, its length in
//       bytes (the prologue check reads it), its convention and its signature as the detour
//       takes it (thiscall: `self` first, in ECX).
//   WXL_POINT_SITE(Ident, address, args)
//       an inlined copy of a point's function: a mid-function hook at the address runs the
//       point's Before handlers with each argument read where `args` says ("ecx,[esp+8]").
//   WXL_POINT_X86_ABSENT(Ident, why)
//       a point of wxl/points.def x86 cannot detour, and why: what find() and list() tell a mod.
//   WXL_POINT_X86_DEINLINED(Ident, name, Parent, ret, params)
//       a point the 2008 compiler inlined into the function of point Parent: the runtime replaces
//       Parent's x86 body with its recompilation (src/deinlined/), in which this function is a
//       real one, entered through the point while it has handlers. Its signature as the contract
//       carries it (a reference is its address).

#ifndef WXL_POINT_X86_DEINLINED
#define WXL_POINT_X86_DEINLINED(Ident, name, Parent, ret, params)
#define WXL_POINT_X86_DEINLINED_DEFAULTED
#endif
#ifndef WXL_POINT_X86
#error "define WXL_POINT_X86(Ident, name, address, length, conv, ret, params) before including x86.def"
#endif
#ifndef WXL_POINT_SITE
#error "define WXL_POINT_SITE(Ident, address, args) before including x86.def"
#endif
#ifndef WXL_POINT_X86_ABSENT
#error "define WXL_POINT_X86_ABSENT(Ident, why) before including x86.def"
#endif

"""]
    for p in points:
        if not p.x86:
            out.append('WXL_POINT_X86_ABSENT(%s, "x64 only: %s")\n' % (p.ident, p.x86_why))
            continue
        params = ", ".join("%s %s" % (t, n) for t, n in p.contract_params())
        if p.deinlined_in is not None:
            out.append('WXL_POINT_X86_DEINLINED(%s, "%s", %s, %s, (%s))\n'
                       % (p.ident, p.name, p.deinlined_in.ident, p.ret_kind[1], params))
            continue
        out.append('WXL_POINT_X86(%s, "%s", %s, %d, %s, %s, (%s))\n'
                   % (p.ident, p.name, column_hex(p.address), p.length, p.convention, p.ret_kind[1], params))
        for address, args, _ in p.sites:
            out.append('WXL_POINT_SITE(%s, %s, "%s")\n' % (p.ident, column_hex(address), ",".join(args)))
    out.append("\n#ifdef WXL_POINT_X86_DEINLINED_DEFAULTED\n#undef WXL_POINT_X86_DEINLINED\n"
               "#undef WXL_POINT_X86_DEINLINED_DEFAULTED\n#endif\n")
    return "".join(out)


# --- sdk/include/wxl/deinlined.def ------------------------------------------------------------

def deinlined_def(points):
    out = [HEADER, """//
// The functions the x86 compiler inlined that the stock client's runtime makes real again: the
// shared list of de-inlined points, which every runtime and mod can read. Columns:
//
//   WXL_DEINLINED(Ident, name, parent, parent_address)
//
//   Ident, name     the point (a row of wxl/points.def), attached to like any other
//   parent          the point whose function Wow.exe 12340 inlined it into; while the point has
//                   handlers, the x86 runtime replaces that function's body with its recompilation
//                   from the fork, in which `name` is called rather than copied
//   parent_address  that function's address in Wow.exe 12340
//
// On the recompiled client (x64) every one of them is a function of its own already. A copy
// inlined into a function that is not a parent here is not reached on x86 (generate_points.py
// --coverage counts them).

#ifndef WXL_DEINLINED
#error "define WXL_DEINLINED(Ident, name, parent, parent_address) before including wxl/deinlined.def"
#endif

"""]
    for p in points:
        if p.deinlined_in is not None:
            out.append('WXL_DEINLINED(%s, "%s", "%s", %s)\n'
                       % (p.ident, p.name, p.deinlined_in.name, column_hex(p.deinlined_in.address)))
    out.append(MSVC_TAIL)
    return "".join(out)


# --- client/WarcraftXL/Points.gen.h --------------------------------------------------------------

def local_type(spelled):
    """The type of a local copy of a parameter: top-level const dropped, so its address is a
    void*."""
    t = spelled.strip()
    if "*" in t:
        t = t.rstrip()
        while t.endswith("const"):
            t = t[:-5].rstrip()
        return t
    return t[6:].strip() if t.startswith("const ") else t


def client_macro(p):
    n = p.index
    names = (["self"] if p.member else []) + [x.name for x in p.params]
    macro_params = ", ".join("p%d" % i for i in range(len(names)))
    # A reference travels as its address: the lambda takes a pointer, the original is called with
    # what it points at, and a handler writes through it as through any pointer argument.
    refs = ([False] if p.member else []) + [x.reference for x in p.params]
    types = ([p.self_type + "*"] if p.member else []) + [
        local_type(x.spelled.replace("&", "").strip()) + "*" if x.reference else local_type(x.spelled)
        for x in p.params]
    returns = p.returns.strip() != "void"
    ret = local_type(p.returns)
    # The attached path is a lambda of its own, kept out of line: the function's frame holds
    # nothing of it, so an unattached point is the test of its byte and a branch, no more.
    lines = ["if (::wxl::point::Enters(%d)) {" % n]
    params = ", ".join("%s wxl_a%d" % (t, i) for i, t in enumerate(types))
    lines.append("    %s[](%s) WXL_POINT_COLD%s {" % ("return " if returns else "", params,
                                                      " -> %s" % ret if returns else ""))
    if returns:
        lines.append("        %s wxl_result{};" % ret)
    lines.append("        void* const wxl_args[] = {%s};" % ", ".join("&wxl_a%d" % i for i in range(len(types))))
    unpack = [("**" if refs[i] else "*") + "static_cast<%s*>(wxl_a_[%d])" % (types[i], i) for i in range(len(types))]
    if p.member:
        call = "(%s)->%s(%s)" % (unpack[0], p.base_name, ", ".join(unpack[1:]))
    else:
        call = "%s(%s)" % (p.base_name, ", ".join(unpack))
    lines.append("        ::wxl::point::Enter(%d, wxl_args, %s, [](void* const* wxl_a_, void* wxl_r_) {"
                 % (n, "&wxl_result" if returns else "nullptr"))
    lines.append("            const ::wxl::point::Bypass wxl_bypass(%d);" % n)
    if returns:
        lines.append("            *static_cast<%s*>(wxl_r_) = %s;" % (ret, call))
    else:
        lines.append("            static_cast<void>(wxl_r_);")
        lines.append("            %s;" % call)
    lines.append("        });")
    if returns:
        lines.append("        return wxl_result;")
    lines.append("    }(%s);" % ", ".join(("&p%d" if refs[i] else "p%d") % i for i in range(len(names))))
    if not returns:
        lines.append("    return;")
    lines.append("}")
    width = max(len(l) for l in lines) + 2
    body = " \\\n".join("    " + l.ljust(width) for l in lines)
    return "// %s (%s)\n#define WXL_POINT_%d(%s) \\\n%s\n" % (p.name, p.lowered, n, macro_params, body.rstrip())


def client_header(points):
    out = [HEADER,
           """//
// The recompiled client's side of wxl.point: one macro per point, which
// core/tools/points/insert_points.py writes as the first statement of the point's function:
//
//     int32_t NetClient::ProcessMessage(uint32_t timeReceived, CDataStore* msg, int32_t unused_a4) {
//         WXL_POINT_4(this, timeReceived, msg, unused_a4); // wxl.point
//
// Unattached, a point is one load of its byte in g_armed and a branch not taken. Attached, the
// macro hands the runtime the addresses of copies of the arguments and a function that calls the
// original: the same function again, through a qualified call, with the point bypassed once on
// this thread. Included through WarcraftXL/Points.h, which defines what the macros call; on Win32,
// which carries no runtime, every macro is empty.

#pragma once

#define WXL_POINT_COUNT %du

/// "name: lowered" of every point in id order: the runtime compares them with its own table.
#define WXL_POINT_ROWS { %s }

#if defined(WXL_POINT_LIVE)

""" % (len(points), ", ".join('"%s: %s"' % (p.name, p.lowered) for p in points))]
    for p in points:
        if p.x64:
            out.append(client_macro(p))
            out.append("\n")
    out.append("#else\n\n")
    for p in points:
        if p.x64:
            out.append("#define WXL_POINT_%d(...) static_cast<void>(0)\n" % p.index)
    out.append("\n#endif\n")
    return "".join(out)


# --- Coverage ----------------------------------------------------------------------------------

def read_pe(path):
    data = Path(path).read_bytes()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    count = struct.unpack_from("<H", data, pe + 6)[0]
    optional = struct.unpack_from("<H", data, pe + 20)[0]
    base = struct.unpack_from("<I", data, pe + 24 + 28)[0]
    sections = []
    for i in range(count):
        o = pe + 24 + optional + 40 * i
        name = data[o:o + 8].rstrip(b"\0").decode("ascii", "replace")
        vsize, va, rsize, raw = struct.unpack_from("<IIII", data, o + 8)
        sections.append((name, base + va, data[raw:raw + rsize]))
    return sections


def binary_references(sections, target):
    calls = jumps = data_refs = 0
    packed = struct.pack("<I", target)
    for name, va, body in sections:
        at = body.find(packed)
        while at >= 0:
            data_refs += 1
            at = body.find(packed, at + 1)
        if name != ".text":
            continue
        for at in range(len(body) - 4):
            op = body[at]
            if op != 0xE8 and op != 0xE9:
                continue
            if va + at + 5 + struct.unpack_from("<i", body, at + 1)[0] == target:
                if op == 0xE8:
                    calls += 1
                else:
                    jumps += 1
    return calls, jumps, data_refs


def source_sites(client, point):
    """(calls, references) of a point's function in the fork's .cpp files, its definition aside."""
    import re
    tail = point.base_name.split("::")[-1]
    owner = point.base_name.split("::")[-2] if "::" in point.base_name else None
    call = re.compile(r"(->|\.|::|[^\w:])" + re.escape(tail) + r"\s*\(")
    ref = re.compile(r"&?\b" + (re.escape(owner) + r"::" if owner else "") + re.escape(tail) + r"\b(?!\s*\()")
    calls = refs = 0
    for path in sorted(client.rglob("*.cpp")):
        rel = path.relative_to(client)
        if rel.parts[0] in ("ThirdParty", "build", "bin", "out") or "Win32" in rel.parts:
            continue
        raw = path.read_text(encoding="utf-8", errors="replace")
        if tail not in raw:
            continue
        text = table.cxx.strip_cxx(raw)
        if owner and re.search(r"\b(?!%s\b)\w+::%s\s*\([^;]*\)\s*(const\s*)?\{" % (re.escape(owner), re.escape(tail)), text):
            continue  # a file of another class's function of that name
        for line in text.split("\n"):
            if tail not in line or "wxl::seam::" in line.replace(" ", ""):
                continue
            if point.base_name + "(" in line.replace(" ", "") and line.rstrip().endswith("{"):
                continue  # the definition
            for m in call.finditer(line):
                if m.group(1) == "::" and owner and not line[:m.start()].endswith(owner):
                    continue
                calls += 1
            if ref.search(line) and "(" not in line[line.find(tail) + len(tail):][:1]:
                refs += 1
    return calls, refs


def coverage(points, client, binary):
    sections = read_pe(binary)
    rows = []
    for p in points:
        if not p.x86:
            rows.append((p, None, None, "no x86 body: " + p.x86_why))
            continue
        if p.deinlined_in is not None:
            rows.append((p, None, None, "de-inlined in %s's recompiled body; a copy inlined anywhere else "
                                        "is not reached" % p.deinlined_in.name))
            continue
        calls, jumps, data_refs = binary_references(sections, p.address)
        src_calls, src_refs = source_sites(client, p)
        seen = calls + jumps + data_refs + len(p.sites)
        expected = src_calls + src_refs
        if seen >= expected:
            verdict = "covered"
        else:
            verdict = "x86 misses %d caller(s): inlined copies want site lines" % (expected - seen)
        rows.append((p, (calls, jumps, data_refs, len(p.sites)), (src_calls, src_refs), verdict))
    return rows


# --- Main --------------------------------------------------------------------------------------

def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--list", type=Path, default=CORE / "include" / "wxl" / "points" / "points.txt")
    parser.add_argument("--client", type=Path, required=True, help="the client fork's checkout")
    parser.add_argument("--sdk", type=Path, default=CORE.parent / "sdk", help="the sdk's checkout")
    parser.add_argument("--offsets", type=Path, default=CORE / "include" / "wxl" / "offsets" / "generated")
    parser.add_argument("--x86", type=Path, default=CORE / "include" / "wxl" / "points" / "x86.def",
                        help="where the x86 table goes")
    parser.add_argument("--check", action="store_true", help="fail when a generated file differs")
    parser.add_argument("--coverage", action="store_true", help="report each point's x86 coverage")
    parser.add_argument("--binary", default=None, help="with --coverage: Wow.exe 12340 (default $WXL_WOW_EXE)")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args(argv)

    try:
        points, problems = table.load(args.list.resolve(), args.client.resolve(), args.offsets.resolve())
    except table.Problem as trouble:
        print("generate_points: %s" % trouble, file=sys.stderr)
        return 2
    if problems:
        print("generate_points: %d problem(s) in the point list" % len(problems), file=sys.stderr)
        for problem in problems:
            print("  " + problem, file=sys.stderr)
        return 1

    if args.coverage:
        import os
        binary = args.binary or os.environ.get("WXL_WOW_EXE")
        if not binary:
            print("generate_points: --coverage needs --binary or $WXL_WOW_EXE", file=sys.stderr)
            return 2
        print("%-28s %-11s %21s %15s  %s" % ("point", "address", "binary call/jmp/ref/site",
                                             "source call/ref", "x86 coverage"))
        missing = 0
        for p, seen, expected, verdict in coverage(points, args.client.resolve(), binary):
            if seen is None:
                print("%-28s %-11s %21s %15s  %s" % (p.name, "-", "-", "-", verdict))
                continue
            print("%-28s 0x%08X  %21s %15s  %s" % (p.name, p.address, "%d/%d/%d/%d" % seen,
                                                   "%d/%d" % expected, verdict))
            missing += verdict != "covered"
        return 0

    outputs = {
        args.sdk.resolve() / "include" / "wxl" / "points.def": contract_def(points),
        args.x86.resolve(): x86_def(points),
        args.client.resolve() / "WarcraftXL" / "Points.gen.h": client_header(points),
        args.sdk.resolve() / "include" / "wxl" / "deinlined.def": deinlined_def(points),
    }
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        if args.check:
            stale.append(path)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            if not args.quiet:
                print("generate_points: wrote %s" % path)
    if stale:
        print("generate_points: %d table(s) are not what points.txt and the fork give; run "
              "core/tools/points/generate_points.py --client <fork> --sdk <sdk> and commit:"
              % len(stale), file=sys.stderr)
        for path in stale:
            print("  " + str(path), file=sys.stderr)
        return 1
    if not args.quiet:
        print("generate_points: %d point(s), %d on x86, %d on x64%s"
              % (len(points), sum(p.x86 for p in points), sum(p.x64 for p in points),
                 ", tables current" if args.check else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
